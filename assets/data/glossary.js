/* 把 tooltip 行為掛到頁面上（由 core.js 呼叫，一般不需要自己叫）*/
export function initGlossary(root = document) {
  let pop = document.getElementById('term-pop');
  if (!pop) {
    pop = document.createElement('div');
    pop.id = 'term-pop';
    pop.setAttribute('role', 'tooltip');
    document.body.appendChild(pop);
  }

  const show = (el) => {
    const key = el.dataset.term || el.textContent.trim();
    const text = GLOSSARY[key];
    if (!text) return;
    pop.innerHTML = `<b>${key}</b>${text}`;
    pop.classList.add('show');
    const r = el.getBoundingClientRect();
    // 先放在元素下方，超出視窗就翻到上方
    const pw = Math.min(280, window.innerWidth - 24);
    pop.style.maxWidth = pw + 'px';
    let left = Math.min(Math.max(8, r.left), window.innerWidth - pw - 8);
    let top = r.bottom + 8;
    if (top + pop.offsetHeight > window.innerHeight - 8) top = Math.max(8, r.top - pop.offsetHeight - 8);
    pop.style.left = left + 'px';
    pop.style.top = top + 'px';
  };
  const hide = () => pop.classList.remove('show');

  root.querySelectorAll('[data-term]').forEach(el => {
    if (el.dataset.termBound) return;
    el.dataset.termBound = '1';
    if (el.tagName !== 'BUTTON' && !el.hasAttribute('tabindex')) el.setAttribute('tabindex', '0');
    if (!el.classList.contains('term')) el.classList.add('term');
    el.setAttribute('aria-label', `名詞解釋：${el.dataset.term || el.textContent.trim()}`);
    el.addEventListener('mouseenter', () => show(el));
    el.addEventListener('focus', () => show(el));
    el.addEventListener('mouseleave', hide);
    el.addEventListener('blur', hide);
    el.addEventListener('click', (e) => { e.preventDefault(); show(el); });
  });
  window.addEventListener('scroll', hide, { passive: true });
}
